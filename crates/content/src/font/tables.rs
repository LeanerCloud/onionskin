/// Metrics for a Base 14 font, or `None` if `base_font` is not one of them.
///
/// Strips an `ABCDEF+` subset prefix and matches case-insensitively against the
/// canonical names plus the substitution aliases Acrobat accepts. Never falls
/// back to a default face: an unrecognised name is an error for the caller.
pub fn base14_metrics(base_font: &str) -> Option<&'static Base14> {
    let bytes = base_font.as_bytes();
    let stripped =
        if bytes.len() > 7 && bytes[6] == b'+' && bytes[..6].iter().all(|b| b.is_ascii_uppercase())
        {
            &base_font[7..]
        } else {
            base_font
        };
    let key = stripped.to_ascii_lowercase();
    ALIASES
        .binary_search_by_key(&key.as_str(), |&(n, _)| n)
        .ok()
        .map(|i| ALIASES[i].1)
}

