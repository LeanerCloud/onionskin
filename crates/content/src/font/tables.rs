/// Maps an Adobe glyph name to its Unicode scalar value.
///
/// Covers the names used by the encoding tables above, every glyph named by a
/// Base 14 AFM, and the common ligature and currency extras. The algorithmic
/// `uniXXXX`, `uXXXXXX`, `gNN` and `cidNN` forms are deliberately absent; the
/// caller resolves those itself. Returns `None` for an unknown name.
pub fn glyph_name_to_unicode(name: &str) -> Option<char> {
    AGL.binary_search_by_key(&name, |&(n, _)| n)
        .ok()
        .map(|i| AGL[i].1)
}

