/// Glyph widths for one Base 14 face, in glyph space units (1/1000 em).
///
/// `names` is sorted; `widths` is parallel to it.
pub struct Base14 {
    pub names: &'static [&'static str],
    pub widths: &'static [u16],
}

impl Base14 {
    /// Width of `glyph` in 1/1000 em, or `None` if the face has no such glyph.
    pub fn width(&self, glyph: &str) -> Option<u16> {
        self.names
            .binary_search_by_key(&glyph, |&n| n)
            .ok()
            .map(|i| self.widths[i])
    }
}

